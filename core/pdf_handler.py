import re
import fitz

from core.diagnostics import extract_pdf_metadata_from_doc, quick_diagnostics


def _sanitize_pdf_cmaps(doc: fitz.Document, log) -> int:
    """
    Repairs malformed ToUnicode CMap streams (e.g., PDFs generated by Mac OS X Quartz PDFContext
    that map Symbol font em-dashes as '<21>< 23af f8e7 >' with internal spaces and PUA characters,
    which otherwise causes pypdfium2/Marker to extract '!' instead of '—').
    Returns the number of repaired CMap streams.
    """
    fixed_count = 0
    for xref in range(1, doc.xref_length()):
        try:
            if not doc.xref_is_stream(xref):
                continue
            raw = doc.xref_stream(xref)
            if not raw or (b"begincmap" not in raw and b"beginbfchar" not in raw):
                continue
            new_raw = re.sub(rb"<\s*23af\s*f8e7\s*>", b"<2014>", raw, flags=re.IGNORECASE)
            new_raw = re.sub(rb"<\s*f8e7\s*>", b"<2014>", new_raw, flags=re.IGNORECASE)
            if new_raw != raw:
                doc.update_stream(xref, new_raw)
                fixed_count += 1
        except Exception:
            continue
    if fixed_count:
        log(f"-> Sanitized {fixed_count} corrupted ToUnicode CMap stream(s) (fixed Symbol em-dashes).")
    return fixed_count


def extract_pdf_metadata(pdf_path: str) -> dict[str, str]:
    """
    Extracts embedded title and author metadata from the source PDF if available.
    Ignores generic placeholder values or raw filenames.
    """
    try:
        doc = fitz.open(pdf_path)
        try:
            return extract_pdf_metadata_from_doc(doc, pdf_path)
        finally:
            doc.close()
    except Exception:
        return {"title": "", "author": ""}


def is_born_digital_pdf(pdf_path: str) -> bool:
    """
    Detects whether a PDF has a native selectable vector text layer rather than full-page scans.
    When True, Marker can run with --disable_ocr to preserve 100% of the native text layer
    without introducing optical OCR typos.
    """
    try:
        diag = quick_diagnostics(pdf_path)
        return diag.recommended_ocr_mode == "disable_ocr"
    except Exception:
        return False


def extract_cover_and_content(
    pdf_path: str,
    cover_out: str,
    content_out: str,
    start_page: int = 1,
    log_path: str = "",
) -> dict[str, int | bool]:
    """
    Extracts the cover image and generates a sanitized content PDF while preserving
    the original CID font dictionaries and structural metadata.
    Returns operational telemetry about the extraction step.
    """
    def log(msg: str):
        if log_path:
            with open(log_path, "a", encoding="utf-8") as f:
                f.write(msg + "\n")

    log("🛡️ Extracting Cover and Protecting Content (DNA Preservation Mode)...")
    doc = fitz.open(pdf_path)

    if doc.page_count < start_page:
        doc.close()
        raise ValueError(f"The PDF only has {doc.page_count} pages, cannot start at page {start_page}.")

    # Render the cover using 'clip' directly in visual page coordinates (page.rect),
    # avoiding cover_page.set_cropbox(), which raises "ValueError: CropBox not in MediaBox"
    # on rotated pages (90°/270°) or pages with an offset MediaBox origin.
    cover_page = doc[start_page - 1]
    r = cover_page.rect
    w, h = r.width, r.height

    clip_rect = None
    wide_cover_cropped = False
    if w > h * 1.05:
        log("-> Wide cover detected. Cropping spine...")
        clip_rect = fitz.Rect(r.x0 + w * 0.52, r.y0, r.x1, r.y1)
        wide_cover_cropped = True

    pix = cover_page.get_pixmap(matrix=fitz.Matrix(4, 4), clip=clip_rect)
    pix.save(cover_out)
    log(f"-> Cover saved at: {cover_out}")

    if start_page > 1:
        doc.delete_pages(list(range(start_page - 1)))

    cmaps_repaired = _sanitize_pdf_cmaps(doc, log)

    doc.save(content_out)
    doc.close()

    log("-> Content PDF successfully generated (Original structure maintained).")
    return {
        "wide_cover_cropped": wide_cover_cropped,
        "cmap_issues_repaired": cmaps_repaired,
    }
