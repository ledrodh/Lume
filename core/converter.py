def _log(log_path: str, msg: str):
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(msg + "\n")
    try:
        print(msg)
    except UnicodeEncodeError:
        enc = sys.stdout.encoding or "utf-8"
        print(msg.encode(enc, errors="replace").decode(enc, errors="replace"))


def _find_generated_md(work_dir: str) -> str | None:
    work = Path(work_dir)
    stem = "content"
    candidates = [work / stem / f"{stem}.md", work / f"{stem}.md"]
    for c in candidates:
        if c.exists():
            return str(c)
    all_files = [p for p in work.rglob("*.md") if "_meta" not in p.name and p.is_file()]
    if all_files:
        all_files.sort(key=lambda p: len(p.parts))
        return str(all_files[0])
    return None


def _sanitize_name(text: str, fallback: str = "Book") -> str:
    name = re.sub(r"[^\w\s\-]", "", text or "").strip()
    return name.replace(" ", "_") or fallback


def _sanitize_markdown(md_text: str, pdf_path: str | None = None) -> str:
    """
    Prepares the Markdown generated by Marker before compiling with Pandoc:
    - Removes invalid id/name attributes
    - Repairs OCR-corrupted <sup>&</sup>lt;sup>N</sup> tags
    - Normalizes Symbol font em-dashes ('⎯\uf8e7' or isolated ' ! ')
    - Converts standalone section numbers ('\n\n2.\n\n') into '### 2.' headings (avoiding empty <ol> lists)
    - Recovers standalone section numbers printed without a period ('53') or dropped at page footers ('67.')
    - Escapes paragraph-initial numbers ('44. Text' -> '44\\. Text') so Pandoc preserves original numbering
    """
    md_text = re.sub(r'\s(id|name)=["\'][^"\']+["\']', "", md_text)
    md_text = re.sub(r"<sup>\s*&(?:amp;)?\s*</sup>\s*lt;sup>\s*(\d+)\s*</sup>", r"<sup>\1</sup>", md_text)
    md_text = md_text.replace("\u23af\uf8e7", "—").replace("\uf8e7", "—").replace("\u23af", "—")
    # Handle cases where pypdfium2 extracted a Symbol em-dash as ' ! ' between words/clauses
    md_text = re.sub(r"(?<=\s)!(?=\s|[,\.;:])", "—", md_text)
    md_text = re.sub(r"(?m)^!\s+", "— ", md_text)
    # Standalone section numbers on their own line (e.g., "1.", "2.", ..., "80.") -> centered H3 heading
    md_text = re.sub(r"(?m)^(\d{1,3})\.\s*$", r"### \1.", md_text)

    # Recover sequential section numbers missing due to omitted periods ("53") or page-footer filtering ("67.")
    # Iterate in reverse order to preserve match offsets when modifying md_text
    sec_matches = list(re.finditer(r"(?m)^###\s+(\d{1,3})\.\s*$", md_text))
    if len(sec_matches) >= 2:
        for idx in range(len(sec_matches) - 2, -1, -1):
            curr_num = int(sec_matches[idx].group(1))
            next_num = int(sec_matches[idx + 1].group(1))
            if next_num == curr_num + 2:
                missing_num = curr_num + 1
                span_start = sec_matches[idx].end()
                span_end = sec_matches[idx + 1].start()
                segment = md_text[span_start:span_end]
                # Case 1: The section number is on its own line without a period (e.g., "\n\n53\n\n")
                seg_fixed, count = re.subn(
                    rf"(?m)^[ \t]*{missing_num}[ \t]*$",
                    f"### {missing_num}.",
                    segment,
                    count=1,
                )
                if count > 0:
                    md_text = md_text[:span_start] + seg_fixed + md_text[span_end:]
                elif pdf_path and os.path.exists(pdf_path):
                    # Case 2: The section number ("67.") was on the last line of a PDF page and filtered as a footer
                    try:
                        doc = fitz.open(pdf_path)
                        for page in doc:
                            lines = [l.strip() for l in page.get_text().splitlines() if l.strip()]
                            if len(lines) >= 2 and re.match(rf"^{missing_num}\.?$", lines[-1]):
                                anchor = lines[-2][-35:].strip()
                                if anchor and anchor in segment:
                                    pos = segment.find(anchor) + len(anchor)
                                    seg_fixed = segment[:pos] + f"\n\n### {missing_num}.\n\n" + segment[pos:]
                                    md_text = md_text[:span_start] + seg_fixed + md_text[span_end:]
                                    break
                        doc.close()
                    except Exception:
                        pass

    # Ensure a blank line before and after each ### N. heading for Pandoc
    md_text = re.sub(r"\n*(### \d{1,3}\.)\n*", r"\n\n\1\n\n", md_text)
    # Prevent Pandoc from turning numbered paragraphs (e.g., Synopsis "44. Text...") into renumbered <ol> lists
    md_text = re.sub(r"(?m)^(\d{1,3})\.\s+(?=\S)", r"\1\. ", md_text)
    return md_text


_CHUNKED_MARKER_SCRIPT = """
import os
import re
import sys
import gc
import json
import torch
import fitz
from pathlib import Path
from bs4 import BeautifulSoup
from marker.config.parser import ConfigParser
from marker.models import create_model_dict
from marker.renderers.json import JSONRenderer

pdf_path = sys.argv[1]
work_dir = sys.argv[2]
disable_ocr = sys.argv[3] == "1"
log_path = sys.argv[4]
chunk_size = 50

def log(msg):
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(msg + "\\n")
    try:
        print(msg, flush=True)
    except Exception:
        pass

doc = fitz.open(pdf_path)
total_pages = len(doc)
doc.close()

out_folder = Path(work_dir) / "content"
out_folder.mkdir(parents=True, exist_ok=True)

models = create_model_dict()
md_chunks = []
provenance_blocks = []

def collect_json_blocks(node, default_page):
    b_id = str(getattr(node, "id", "") or "")
    m_page = re.search(r"/page/(\\d+)/", b_id)
    page_num = (int(m_page.group(1)) + 1) if m_page else default_page
    children = getattr(node, "children", None)
    if children:
        for ch in children:
            collect_json_blocks(ch, page_num)
    else:
        raw_html = getattr(node, "html", "") or ""
        if raw_html:
            txt = BeautifulSoup(raw_html, "html.parser").get_text(" ", strip=True)
            if len(txt) >= 15:
                provenance_blocks.append({
                    "page_number": page_num,
                    "block_id": b_id,
                    "block_type": str(getattr(node, "block_type", "")),
                    "text": txt[:400],
                })

for start_idx in range(0, total_pages, chunk_size):
    end_idx = min(start_idx + chunk_size, total_pages)
    page_range_str = f"{start_idx}-{end_idx - 1}"
    log(f"-> Processing pages {start_idx + 1} to {end_idx} of {total_pages}...")

    cli_opts = {
        "output_dir": work_dir,
        "output_format": "markdown",
        "page_range": page_range_str,
        "disable_ocr": disable_ocr,
        "disable_tqdm": True,
    }
    config_parser = ConfigParser(cli_opts)
    converter_cls = config_parser.get_converter_cls()
    converter = converter_cls(
        config=config_parser.generate_config_dict(),
        artifact_dict=models,
        processor_list=config_parser.get_processors(),
        renderer=config_parser.get_renderer(),
        llm_service=config_parser.get_llm_service(),
    )
    with converter.filepath_to_str(pdf_path) as temp_path:
        document = converter.build_document(temp_path)
        md_renderer = converter.resolve_dependencies(converter.renderer)
        rendered = md_renderer(document)
        try:
            json_renderer = converter.resolve_dependencies(JSONRenderer)
            json_out = json_renderer(document)
            for idx_p, page_node in enumerate(getattr(json_out, "children", []) or []):
                collect_json_blocks(page_node, start_idx + idx_p + 1)
        except Exception:
            pass

    md_chunks.append(rendered.markdown.strip())
    if getattr(rendered, "images", None):
        for img_name, img_obj in rendered.images.items():
            img_obj.save(out_folder / img_name)

    del document
    del rendered
    del converter
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

final_md = "\\n\\n".join(md_chunks) + "\\n"
(out_folder / "content.md").write_text(final_md, encoding="utf-8")
(out_folder / "provenance_blocks.json").write_text(
    json.dumps(provenance_blocks, ensure_ascii=False), encoding="utf-8"
)
log(f"-> All {total_pages} pages successfully converted to Markdown ({len(provenance_blocks)} provenance blocks indexed).")
"""


# ─────────────────────────────────────────────────────────────────────────────
# MAIN FUNCTION
# ─────────────────────────────────────────────────────────────────────────────
def process_book(
    pdf_in: str,
    out_dir: str,
    title: str,
    author: str,
    formats: list,
    start_page: int = 1,
    diagnostics: DocumentDiagnostics | None = None,
) -> dict:
    pdf_in = os.path.abspath(pdf_in)
    out_dir = os.path.abspath(out_dir)

    if diagnostics is None or not diagnostics.is_complete:
        diagnostics = full_diagnostics(pdf_in) or quick_diagnostics(pdf_in)

    embedded_meta = extract_pdf_metadata(pdf_in)
    if not title or not title.strip():
        title = (
            diagnostics.embedded_title
            or embedded_meta.get("title")
            or os.path.splitext(os.path.basename(pdf_in))[0]
        )

    if not author or not author.strip():
        author = diagnostics.embedded_author or embedded_meta.get("author") or "Unknown"

    work_dir = os.path.join(out_dir, "workdir")
    marker_in_dir = os.path.join(work_dir, "marker_input")
    log_path = os.path.join(out_dir, "process_log.txt")

    if os.path.exists(work_dir):
        shutil.rmtree(work_dir)
    os.makedirs(marker_in_dir, exist_ok=True)
    os.makedirs(out_dir, exist_ok=True)

    if os.path.exists(log_path):
        os.remove(log_path)

    def log(msg: str):
        _log(log_path, msg)

    # 1. Cover & Content Extraction
    content_pdf = os.path.join(marker_in_dir, "content.pdf")
    cover_jpg = os.path.join(work_dir, "cover.jpg")
    extraction_stats = extract_cover_and_content(pdf_in, cover_jpg, content_pdf, start_page, log_path)

    # 2. OCR / Layout Extraction (Chunked to avoid ArrayMemoryError on large books)
    marker_py = get_marker_python()
    compute_device = _detect_compute_device(marker_py)

    env = os.environ.copy()
    env["TORCH_DEVICE"] = compute_device
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONUTF8"] = "1"

    # Enforce native PyTorch backend across all Marker/Surya submodules
    env["INFERENCE_BACKEND"] = "torch"
    env["SURYA_INFERENCE_BACKEND"] = "torch"
    env["MARKER_INFERENCE_BACKEND"] = "torch"
    env["LAYOUT_BACKEND"] = "torch"
    env["RECOGNITION_BACKEND"] = "torch"
    env["VLM_BACKEND"] = "torch"

    content_pdf_path = os.path.join(marker_in_dir, "content.pdf")
    disable_ocr_flag = "1" if is_born_digital_pdf(content_pdf_path) else "0"

    if disable_ocr_flag == "1":
        log("📄 Native digital text layer detected -> enabling --disable_ocr for 100% text fidelity and 3x speed.")

    log(f"🔍 Running Marker in memory-safe 50-page chunks (device: {compute_device.upper()}, native PyTorch)...")
    log(f"-> Python/Marker environment resolved at: {marker_py}")

    try:
        res_marker = subprocess.run(
            [marker_py, "-c", _CHUNKED_MARKER_SCRIPT, content_pdf_path, work_dir, disable_ocr_flag, log_path],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
        )
    except FileNotFoundError as e:
        log(f"CRITICAL: Could not locate or execute the Marker Python environment.\nAttempted path: {marker_py}\nError: {e}")
        raise RuntimeError(
            f"The Marker Python environment was not found.\n"
            f"Attempted path: {marker_py}"
        ) from e

    if res_marker.returncode != 0:
        log(f"CRITICAL MARKER ERROR:\n{res_marker.stderr}")
        error_tail = res_marker.stderr.strip()[-1000:]
        raise RuntimeError(f"Marker failed! See process_log.txt.\nEnd of error:\n{error_tail}")

    # 3. Locate Generated Markdown
    md_path = _find_generated_md(work_dir)
    if not md_path:
        raise RuntimeError(
            "Marker finished, but did not generate a Markdown file. "
            "Check if the PDF consists only of blank images or has DRM protection."
        )

    # 4. Markdown Sanitization and Base EPUB Compilation via Pandoc
    with open(md_path, "r", encoding="utf-8") as f:
        md_text = f.read()
    md_text = _sanitize_markdown(md_text, content_pdf_path)
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_text)

    log("📦 Generating base EPUB with Pandoc...")
    temp_epub = os.path.join(os.path.dirname(md_path), "temp.epub")

    try:
        pandoc_exe = pypandoc.get_pandoc_path()
    except Exception:
        pandoc_exe = "pandoc"

    pandoc_cmd = [pandoc_exe, md_path, "-o", temp_epub]
    if os.path.exists(cover_jpg):
        pandoc_cmd += ["--epub-cover-image", cover_jpg]

    pandoc_cmd += ["-M", f"title={title}", "-M", f"author={author}"]

    subprocess.run(
        pandoc_cmd,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=os.path.dirname(md_path),
    )

    # 5. HTML Healing, Provenance Mapping & OCF Validation
    base_name = _sanitize_name(title)
    epub_final = os.path.join(out_dir, f"{base_name}.epub")
    blocks_json_path = os.path.join(os.path.dirname(md_path), "provenance_blocks.json")
    provenance = ProvenanceResolver(content_pdf_path, blocks_json_path)
    healing_stats = HealingStats()

    process_epub_html(temp_epub, epub_final, log_path, stats=healing_stats, provenance=provenance)

    validation_summary = validate_epub_structure(epub_final)
    if validation_summary.is_valid:
        log(
            f"🛡️ OCF/EPUB validation passed ({validation_summary.checked_files} files, "
            f"{validation_summary.checked_links} internal links verified)."
        )
    else:
        log(f"⚠️ OCF/EPUB validation found {len(validation_summary.issues)} issue(s).")

    requested_formats = [f.upper() for f in formats]
    generated_files = []
    failed_formats = {}

    if "EPUB" in requested_formats:
        generated_files.append(epub_final)

    # 6. Additional Format Conversions via Calibre (uses temporary files for stdout/stderr instead of PIPE
    # so detached QtWebEngine/Chromium helper processes never block pipe closure on Windows)
    calibre_path = CALIBRE_EXE

    for fmt in requested_formats:
        if fmt in ["AZW3", "PDF"]:
            out_file = os.path.join(out_dir, f"{base_name}.{fmt.lower()}")
            log(f"📱 Converting to {fmt}...")
            try:
                with tempfile.TemporaryFile() as out_f, tempfile.TemporaryFile() as err_f:
                    subprocess.run(
                        [calibre_path, epub_final, out_file],
                        check=True,
                        stdin=subprocess.DEVNULL,
                        stdout=out_f,
                        stderr=err_f,
                        timeout=600,
                    )
                generated_files.append(out_file)
                log(f"✅ Generated: {out_file}")
            except Exception as e:
                failed_formats[fmt] = str(e)
                log(f"⚠ Conversion error ({fmt}): {e}")

    # Remove intermediate EPUB if the user only requested AZW3/PDF and those conversions succeeded
    if "EPUB" not in requested_formats and generated_files and os.path.exists(epub_final):
        try:
            os.remove(epub_final)
        except OSError:
            pass

    export_results = {
        "requested_formats": requested_formats,
        "generated_files": generated_files,
        "failed_formats": failed_formats,
    }

    # 7. Save Structured Restoration Report & Visual Comparison HTML
    report = build_restoration_report(
        pdf_path=pdf_in,
        title=title,
        author=author,
        compute_device=compute_device,
        diagnostics=diagnostics,
        extraction_stats=extraction_stats,
        healing_stats=healing_stats,
        validation=validation_summary,
        export_results=export_results,
    )
    report_json_path = os.path.join(out_dir, "restoration_report.json")
    report.save(report_json_path)
    comparison_html_path = generate_comparison_report(report, content_pdf_path, out_dir)
    log(f"📊 Audit report & visual comparator generated at: {comparison_html_path}")

    if not generated_files and failed_formats:
        details = "; ".join(f"{k}: {v}" for k, v in failed_formats.items())
        raise RuntimeError(f"Failed to generate the requested output format(s): {details}")

    if failed_formats:
        log(f"⚠️ Restoration finished with conversion warnings: {failed_formats}")
    else:
        log("🎉 Restoration complete!")

    return {
        "output_dir": out_dir,
        "generated_files": generated_files,
        "failed_formats": failed_formats,
        "report_path": report_json_path,
        "comparison_html_path": comparison_html_path,
    }
