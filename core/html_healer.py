def heal_html(soup: BeautifulSoup, stats: HealingStats | None = None):
    """Applies Kindle-safe CSS, unwraps false superscripts, removes leaked page numbers, and fixes hyphenation."""
    style_tag = soup.new_tag("style", type="text/css")
    style_tag.string = """
    img { max-width: 100%; height: auto; margin: 1.5em auto; display: block; }
    p { text-align: justify; line-height: 1.5; margin: 0.35em 0; }
    h1, h2, h3, h4 { text-align: center; margin: 1.4em 0 0.7em 0; page-break-after: avoid; }
    .toc-entry { text-align: left; margin: 0.8em 0; overflow: hidden; }
    .toc-title { font-weight: bold; }
    .toc-page { float: right; font-weight: bold; }
    """
    if soup.head:
        soup.head.append(style_tag)

    # 1. Unwrap false <sup> tags generated by Marker on ordinary words/letters (e.g., <sup>é</sup>, <sup>o</sup>, <sup>a</sup>)
    for sup in list(soup.find_all("sup")):
        txt = sup.get_text(strip=True)
        if not txt:
            sup.decompose()
            continue
        # Keep only numeric footnote markers (e.g., 1, (1), [1]) or legitimate short ordinals
        if not re.match(r"^[\(\[]?\d{1,3}[\)\]]?$", txt) and txt not in ("º", "ª"):
            prev_sib = sup.previous_sibling
            next_sib = sup.next_sibling
            need_space_before = prev_sib is not None and not str(prev_sib).endswith(
                (" ", "\n", "(", "[", "«", "“", '"')
            )
            need_space_after = next_sib is not None and not str(next_sib).startswith(
                (" ", "\n", ".", ",", ";", ":", "!", "?", ")", "]", "»", "”", '"')
            )
            replacement = (f" {txt}" if need_space_before else txt) + (" " if need_space_after else "")
            sup.replace_with(NavigableString(replacement))
            if stats is not None:
                stats.false_sups_unwrapped += 1

    # 2. Remove standalone paragraphs that contain only leaked header/footer page numbers (e.g., <p>329</p>)
    for p in list(soup.find_all("p")):
        txt = p.get_text(strip=True)
        if re.match(r"^\d{1,4}$", txt):
            p.decompose()
            if stats is not None:
                stats.leaked_pages_removed += 1

    # 3. Clean PUA characters from Symbol font (⎯\uf8e7 -> —) and join ghost hyphenations across line breaks
    for node in list(soup.find_all(string=True)):
        if node.parent and node.parent.name in ["script", "style"]:
            continue
        orig = str(node)
        text = orig.replace("\xa0", " ").replace("\t", " ")
        dash_fixes = text.count("\u23af\uf8e7") + text.count("\uf8e7") + text.count("\u23af")
        text = text.replace("\u23af\uf8e7", "—").replace("\uf8e7", "—").replace("\u23af", "—")
        if stats is not None and dash_fixes > 0:
            stats.em_dashes_normalized += dash_fixes
        # Only join hyphenated words when the second part starts with a lowercase letter, preserving proper compounds
        text = re.sub(r"([A-Za-zÀ-ÿ]{2,})-\s+([a-zà-ÿ]{2,})", r"\1\2", text)
        if text != orig:
            node.replace_with(NavigableString(text))

    # Merge adjacent NavigableString nodes created by unwrapping <sup> tags
    soup.smooth()


def is_toc_table(table: Tag) -> bool:
    """Detects whether an HTML <table> represents a Table of Contents."""
    rows = table.find_all("tr")
    if len(rows) < 4:
        return False
    page_regex = re.compile(r"(.*?)([IVXLCDMivxlcdmuU]+|\d{1,4})\s*$", re.IGNORECASE)
    hits = sum(
        1
        for r in rows
        if r.find_all(["td", "th"]) and page_regex.search(r.find_all(["td", "th"])[-1].get_text(strip=True))
    )
    return (hits / len(rows)) >= 0.35


def transform_toc_kindle_safe(table: Tag, soup: BeautifulSoup, stats: HealingStats | None = None) -> Tag:
    """Replaces TOC tables with float-based <p> elements that render reliably on Kindle devices."""
    rows = table.find_all("tr")
    entries = []
    page_regex = re.compile(r"^(.*?)(?<!\s)([IVXLCDMivxlcdmuU]+|\d{1,4})\s*$", re.IGNORECASE)

    for row in rows:
        cells = row.find_all(["td", "th"])
        if not cells:
            continue
        m = page_regex.search(cells[-1].get_text(strip=True))
        if m:
            remainder, page = m.group(1).strip(), m.group(2).replace("l", "1").replace("O", "0")
            title = (" ".join(c.get_text(separator=" ", strip=True) for c in cells[:-1]) + " " + remainder).strip()
            level = "sub" if re.match(r"^[IVXLCDM]+\.\s", title, re.IGNORECASE) else "chapter"
            entries.append({"title": title, "page": page, "level": level})

    if stats is not None:
        stats.toc_entries_rebuilt += len(entries)

    nav_div = soup.new_tag("div", attrs={"style": "margin: 2em 0;"})
    for e in entries:
        p = soup.new_tag("p", attrs={"class": "toc-entry"})
        if e["level"] == "sub":
            p["style"] = "padding-left: 1.5em; font-weight: normal;"

        span_title = soup.new_tag("span", attrs={"class": "toc-title"})
        if e["level"] == "sub":
            span_title["style"] = "font-weight: normal;"
        span_title.string = e["title"]

        span_page = soup.new_tag("span", attrs={"class": "toc-page"})
        span_page.string = e["page"]

        p.extend([span_title, span_page])
        nav_div.append(p)
    return nav_div


_TERMINAL_PUNCT = (".", "!", "?", ":", ";", "…", "»", "”", '"', ")", "]")


def _ends_sentence(text: str) -> bool:
    t = text.strip()
    if not t:
        return True
    # Strip trailing footnote numbers attached to the end of a sentence (e.g., »6 .)
    t = re.sub(r"\s*\d{1,3}\s*\.?$", lambda m: "." if m.group(0).strip().endswith(".") else "", t).strip()
    return t.endswith(_TERMINAL_PUNCT)


def _clean_fn_html(html_fragment: str) -> tuple[str, str]:
    """Returns (clean_html, clean_plain_text) while preserving inline <em>/<i>/<strong> tags in footnotes."""
    frag = BeautifulSoup(html_fragment, "html.parser")
    plain = re.sub(r"\s+", " ", frag.get_text()).strip()
    html_str = re.sub(r"\s+", " ", str(frag)).strip()
    return html_str, plain


def _extract_footnotes_from_soup(
    fname: str,
    soup: BeautifulSoup,
    g_notes: dict,
    stats: HealingStats | None = None,
):
    """
    Extracts footnotes across multiple layout formats:
    1) Paragraphs starting with <sup>N</sup> (including multiple <sup>N</sup> notes merged into one <p>)
    2) Continuation of a previous footnote followed by <sup>N</sup> mid-paragraph
    3) Additional paragraphs of a multi-paragraph footnote when the main body sentence was interrupted
    4) Classic format without <sup>: "[1] Text..." or "(1) Text..."
    """
    paragraphs = list(soup.find_all("p"))
    last_fn_num = None
    body_waiting_continuation = False

    i = 0
    while i < len(paragraphs):
        p = paragraphs[i]
        if not p.parent:
            i += 1
            continue

        raw_html = p.decode_contents().strip()
        plain_txt = p.get_text().strip()

        # Case 1: Paragraph starts with <sup>N</sup> (or <sup>(N)</sup>)
        m_sup_start = re.match(r"^\s*<sup>\s*[\(\[]?(\d{1,3})[\)\]]?\s*</sup>\s*(.+)$", raw_html, flags=re.DOTALL)
        if m_sup_start:
            # Normalize inline footnotes glued without <sup> (e.g., "). 53Idem, p.366")
            raw_html_norm = re.sub(r"(?<=[\.\)\;]\s)(\d{1,3})(?=[A-ZÀ-Ý])", r"<sup>\1</sup> ", raw_html)
            parts = re.split(r"<sup>\s*[\(\[]?(\d{1,3})[\)\]]?\s*</sup>", raw_html_norm)
            for idx in range(1, len(parts), 2):
                fnum = parts[idx]
                fhtml, ftext = _clean_fn_html(parts[idx + 1])
                if ftext:
                    g_notes[fnum] = {"text": ftext, "html": fhtml, "file": fname, "refs": []}
                    last_fn_num = fnum
                    if stats is not None:
                        stats.footnotes_extracted += 1
            p.decompose()
            i += 1
            continue

        # Case 2: Previous footnote ended without terminal punctuation and this <p> has the remainder + <sup>N</sup>
        if last_fn_num and last_fn_num in g_notes and not _ends_sentence(g_notes[last_fn_num]["text"]):
            if re.search(r"<sup>\s*[\(\[]?\d{1,3}[\)\]]?\s*</sup>", raw_html):
                parts = re.split(r"<sup>\s*[\(\[]?(\d{1,3})[\)\]]?\s*</sup>", raw_html)
                prefix_html, prefix_txt = _clean_fn_html(parts[0])
                if prefix_txt:
                    g_notes[last_fn_num]["text"] = (g_notes[last_fn_num]["text"] + " " + prefix_txt).strip()
                    g_notes[last_fn_num]["html"] = (g_notes[last_fn_num]["html"] + " " + prefix_html).strip()
                for idx in range(1, len(parts), 2):
                    fnum = parts[idx]
                    fhtml, ftext = _clean_fn_html(parts[idx + 1])
                    if ftext:
                        g_notes[fnum] = {"text": ftext, "html": fhtml, "file": fname, "refs": []}
                        last_fn_num = fnum
                        if stats is not None:
                            stats.footnotes_extracted += 1
                p.decompose()
                i += 1
                continue

        # Case 3: Multi-paragraph footnote continuation while body sentence is awaiting continuation
        if (
            last_fn_num
            and body_waiting_continuation
            and plain_txt
            and plain_txt[0].isupper()
            and i + 1 < len(paragraphs)
        ):
            next_txt = paragraphs[i + 1].get_text().strip()
            if next_txt and next_txt[0].islower():
                extra_html, extra_txt = _clean_fn_html(raw_html)
                g_notes[last_fn_num]["text"] += " " + extra_txt
                g_notes[last_fn_num]["html"] += " " + extra_html
                p.decompose()
                i += 1
                continue

        # Case 4: Classic format without <sup>: "[1] Text" or "(1) Text"
        m_classic = re.match(r"^[\[\(](\d{1,3})[\]\)]\s+(.+)", plain_txt, flags=re.DOTALL)
        if m_classic:
            fnum = m_classic.group(1)
            ftext = re.sub(r"\s+", " ", m_classic.group(2)).strip()
            g_notes[fnum] = {"text": ftext, "html": ftext, "file": fname, "refs": []}
            last_fn_num = fnum
            if stats is not None:
                stats.footnotes_extracted += 1
            p.decompose()
            i += 1
            continue

        # Regular body paragraph
        last_fn_num = None
        body_waiting_continuation = not _ends_sentence(plain_txt)
        i += 1


def _stitch_broken_paragraphs(
    soup: BeautifulSoup,
    stats: HealingStats | None = None,
    provenance: ProvenanceResolver | None = None,
):
    """
    Rejoins body paragraphs that were split across page breaks (and across removed footnote blocks).
    Also strips leaked running page numbers at the end of a line before a page break.
    """
    paragraphs = [p for p in soup.find_all("p") if p.parent and "toc-entry" not in (p.get("class") or [])]
    if stats is not None:
        stats.paragraphs_inspected += len(paragraphs)

    i = 0
    while i < len(paragraphs) - 1:
        p1 = paragraphs[i]
        p2 = paragraphs[i + 1]

        # Only stitch if p1 and p2 share the same parent and have no intervening structural tags (h1/h2/h3/blockquote)
        if p1.parent != p2.parent:
            i += 1
            continue
        intervening = False
        sib = p1.next_sibling
        while sib is not None and sib != p2:
            if isinstance(sib, Tag):
                intervening = True
                break
            sib = sib.next_sibling
        if intervening:
            i += 1
            continue

        t1_orig = p1.get_text().strip()
        t2_orig = p2.get_text().strip()
        t1 = t1_orig
        t2 = t2_orig
        if not t1 or not t2:
            i += 1
            continue

        # Strip leaked page number at the end of p1 before a lowercase continuation
        if re.search(r"\s+\d{1,3}$", t1) and t2[0].islower():
            text_nodes = [n for n in p1.find_all(string=True) if str(n).strip()]
            if text_nodes:
                last_node = text_nodes[-1]
                cleaned = re.sub(r"\s+\d{1,3}\s*$", "", str(last_node))
                last_node.replace_with(NavigableString(cleaned))
                t1 = p1.get_text().strip()
                if stats is not None:
                    stats.leaked_pages_removed += 1

        # Stitch condition: p1 does not end a sentence and p2 continues with lowercase (or p1 ends with a dangling article/preposition)
        p1_incomplete = not _ends_sentence(t1)
        p1_ends_dangling_article = bool(
            re.search(r"(?:^|\s|\.\s+)([OA]|Os|As|Um|Uma|De|Da|Do|Em|Na|No|Por|Para|Que|Se|The|Of|In|To|And)$", t1)
        )
        p2_continues = t2[0].islower() or p1_ends_dangling_article

        if p1_incomplete and p2_continues:
            p1.append(NavigableString(" "))
            for child in list(p2.contents):
                p1.append(child.extract())
            p2.decompose()
            paragraphs.pop(i + 1)

            if stats is not None:
                stats.paragraphs_stitched += 1
                stitched_Samples = [s for s in stats.samples if s.category == "paragraph_stitching"]
                if len(stitched_Samples) < 4:
                    merged_txt = p1.get_text().strip()
                    src_pages, blk_ids = (
                        provenance.resolve(t1, t2) if provenance is not None else ([], [])
                    )
                    stats.samples.append(
                        TransformationSample(
                            sample_id=f"stitch-{stats.paragraphs_stitched}",
                            category="paragraph_stitching",
                            source_pages=src_pages,
                            block_ids=blk_ids,
                            original_excerpt=f"[Part 1]: ...{t1_orig[-140:]}\n[Page Break / Footnote Gap]\n[Part 2]: {t2_orig[:140]}...",
                            restored_excerpt=merged_txt[:320] + ("..." if len(merged_txt) > 320 else ""),
                            description="Reconstructed sentence split across page boundary and removed intervening footer noise.",
                        )
                    )
        else:
            i += 1

    soup.smooth()


def _package_epub(source_dir: Path, epub_out: str):
    """
    Packages an extracted EPUB directory into a W3C EPUB 3.3 OCF-compliant archive:
    - 'mimetype' is written as the very first entry using ZIP_STORED (uncompressed).
    - All other container and content files are written using ZIP_DEFLATED with POSIX paths.
    """
    mimetype_file = source_dir / "mimetype"
    with zipfile.ZipFile(epub_out, "w", zipfile.ZIP_DEFLATED) as zo:
        if mimetype_file.exists():
            zo.write(mimetype_file, "mimetype", compress_type=zipfile.ZIP_STORED)
        else:
            zinfo = zipfile.ZipInfo("mimetype")
            zinfo.compress_type = zipfile.ZIP_STORED
            zo.writestr(zinfo, b"application/epub+zip")

        for f in sorted(source_dir.rglob("*")):
            if f.is_file() and f != mimetype_file:
                arcname = f.relative_to(source_dir).as_posix()
                zo.write(f, arcname, compress_type=zipfile.ZIP_DEFLATED)


def process_epub_html(
    epub_in: str,
    epub_out: str,
    log_path: str = "",
    stats: HealingStats | None = None,
    provenance: ProvenanceResolver | None = None,
) -> HealingStats:
    """Triple-Pass: Reconstructs the EPUB applying heals to HTML, Paragraphs, TOC, and Footnotes."""
    if stats is None:
        stats = HealingStats()

    def log(msg: str):
        if log_path:
            with open(log_path, "a", encoding="utf-8") as f:
                f.write(msg + "\n")

    log("⚙️ Starting Triple-Pass on HTML (Paragraphs, TOC, and Footnotes)...")
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        with zipfile.ZipFile(epub_in, "r") as z:
            z.extractall(tmp_path)

        xhtmls = sorted(list((tmp_path / "EPUB" / "text").glob("*.xhtml")))
        soups = {x.name: BeautifulSoup(x.read_text(encoding="utf-8"), "html.parser") for x in xhtmls}

        for s in soups.values():
            heal_html(s, stats)

        # --- PHASE 1: Global Footnote Memory & Paragraph Stitching ---
        g_notes = {}
        for fname, s in soups.items():
            _extract_footnotes_from_soup(fname, s, g_notes, stats)
            _stitch_broken_paragraphs(s, stats, provenance)

        toc_state = {"found": False, "finished": False}
        ocr_map = {"l": "1", "I": "1", "O": "0", "º": "0", "°": "0"}

        def heal_ocr_errors(match):
            base, error = match.group(1), match.group(2)
            if not base:
                start_idx = match.start(2)
                if start_idx > 0 and match.string[start_idx - 1].isalpha():
                    return match.group(0)
            candidate = base + ocr_map.get(error, "")
            if candidate in g_notes:
                return candidate
            return match.group(0)

        # --- PHASE 2: Link Hunting and TOC ---
        # Matches footnote numbers attached to words, ellipses (…), closing quotes (», ”, "), or closing brackets,
        # even when followed by a period at the end of a sentence (e.g., «...demais»11. No ano...).
        regex_note = re.compile(r"([A-Za-zÀ-ÿ»”\"’\'\)\]…])(\s*)(\d{1,3})(?![A-Za-z0-9À-ÿº°])")

        for fname, s in soups.items():
            for table in s.find_all("table"):
                stats.toc_tables_inspected += 1
                if is_toc_table(table) and not toc_state["finished"]:
                    toc_state["found"] = True
                    table.replace_with(transform_toc_kindle_safe(table, s, stats))
                elif toc_state["found"]:
                    toc_state["finished"] = True

            for sup in s.find_all("sup"):
                raw_num = sup.get_text(strip=True).strip("()[]")
                if raw_num in g_notes and not sup.find_parent("a"):
                    ref_id = f"ref-{raw_num}-{len(g_notes[raw_num]['refs']) + 1}"
                    g_notes[raw_num]["refs"].append({"file": fname, "id": ref_id})
                    href = (
                        f"{g_notes[raw_num]['file']}#fn-{raw_num}"
                        if g_notes[raw_num]["file"] != fname
                        else f"#fn-{raw_num}"
                    )
                    a = s.new_tag(
                        "a",
                        attrs={
                            "id": ref_id,
                            "href": href,
                            "epub:type": "noteref",
                            "style": "text-decoration: none; color: #d35400; font-weight: bold;",
                        },
                    )
                    sup.wrap(a)

            for p in s.find_all("p"):
                for node in list(p.find_all(string=True)):
                    if node.parent.name in ["sup", "a"]:
                        continue
                    text_fixed = re.sub(r"(\d{1,2})([lIOº°])\b", heal_ocr_errors, str(node))

                    # Check whether a footnote number sits at the start of this text node right after an inline tag (e.g., <em>word</em>90,)
                    leading_m = None
                    if (
                        node.previous_sibling is not None
                        and getattr(node.previous_sibling, "name", None) in ("em", "i", "strong", "b", "span")
                        and node.previous_sibling.get_text()
                        and re.search(r"[A-Za-zÀ-ÿ»”\"’\'\)\]…]$", node.previous_sibling.get_text())
                    ):
                        prev_tag_text = node.previous_sibling.get_text()
                        m0 = re.match(r"^(\s*)(\d{1,3})(?![A-Za-z0-9À-ÿº°])", text_fixed)
                        if m0:
                            lead_space, lead_num = m0.group(1), m0.group(2)
                            if (not lead_space or prev_tag_text[-1] in ("»", "”", '"', ")", "]", "…")) and lead_num in g_notes and int(lead_num) < 500:
                                leading_m = m0

                    matches = list(regex_note.finditer(text_fixed))
                    if leading_m or matches:
                        new_content = []
                        last_pos = 0
                        changed = False
                        if leading_m:
                            num = leading_m.group(2)
                            changed = True
                            ref_id = f"ref-{num}-{len(g_notes[num]['refs']) + 1}"
                            g_notes[num]["refs"].append({"file": fname, "id": ref_id})
                            href = (
                                f"{g_notes[num]['file']}#fn-{num}"
                                if g_notes[num]["file"] != fname
                                else f"#fn-{num}"
                            )
                            a = s.new_tag(
                                "a",
                                attrs={
                                    "id": ref_id,
                                    "href": href,
                                    "epub:type": "noteref",
                                    "style": "text-decoration: none; color: #d35400; font-weight: bold; vertical-align: super; font-size: 0.75em;",
                                },
                            )
                            a.string = num
                            new_content.append(a)
                            last_pos = leading_m.end()

                        for m in matches:
                            if m.start() < last_pos:
                                continue
                            prev, space, num = m.group(1), m.group(2), m.group(3)
                            # If preceded by whitespace, only accept after closing quotes/brackets and when not a numbered list item ("6. ")
                            if space:
                                if prev not in ("»", "”", '"', ")", "]", "…"):
                                    continue
                                after = text_fixed[m.end():]
                                if after.startswith(".") and prev not in ("»", "”", '"'):
                                    continue
                            if num in g_notes and int(num) < 500:
                                changed = True
                                new_content.append(NavigableString(text_fixed[last_pos:m.start()] + prev))
                                ref_id = f"ref-{num}-{len(g_notes[num]['refs']) + 1}"
                                g_notes[num]["refs"].append({"file": fname, "id": ref_id})
                                href = (
                                    f"{g_notes[num]['file']}#fn-{num}"
                                    if g_notes[num]["file"] != fname
                                    else f"#fn-{num}"
                                )
                                a = s.new_tag(
                                    "a",
                                    attrs={
                                        "id": ref_id,
                                        "href": href,
                                        "epub:type": "noteref",
                                        "style": "text-decoration: none; color: #d35400; font-weight: bold; vertical-align: super; font-size: 0.75em;",
                                    },
                                )
                                a.string = num
                                new_content.append(a)
                                last_pos = m.end()
                        if changed:
                            new_content.append(NavigableString(text_fixed[last_pos:]))
                            parent = node.parent
                            idx = list(parent.contents).index(node)
                            node.extract()
                            for item in reversed(new_content):
                                parent.insert(idx, item)
                        elif text_fixed != str(node):
                            node.replace_with(NavigableString(text_fixed))
                    elif text_fixed != str(node):
                        node.replace_with(NavigableString(text_fixed))

                # Remove spurious spaces before punctuation right after footnote links (e.g., </a> , -> </a>,)
                for a_tag in p.find_all("a", attrs={"epub:type": "noteref"}):
                    nxt = a_tag.next_sibling
                    if isinstance(nxt, NavigableString):
                        cleaned_nxt = re.sub(r"^\s+([\.,;:\!\?])", r"\1", str(nxt))
                        if cleaned_nxt != str(nxt):
                            nxt.replace_with(NavigableString(cleaned_nxt))

        # --- PHASE 3: Footnote Reinjection & Telemetry ---
        linked_count = 0
        unlinked_count = 0
        for num_key, fn_data in sorted(g_notes.items(), key=lambda kv: int(kv[0])):
            if fn_data["refs"]:
                linked_count += 1
                fn_samples = [s for s in stats.samples if s.category == "footnote_linking"]
                if len(fn_samples) < 4:
                    src_pages, blk_ids = (
                        provenance.resolve(fn_data["text"]) if provenance is not None else ([], [])
                    )
                    stats.samples.append(
                        TransformationSample(
                            sample_id=f"fn-{num_key}",
                            category="footnote_linking",
                            source_pages=src_pages,
                            block_ids=blk_ids,
                            original_excerpt=f"Unlinked footer note {num_key}: {fn_data['text'][:180]}",
                            restored_excerpt=(
                                f"<li id='fn-{num_key}'><strong>[{num_key}]</strong> "
                                f"{fn_data['text'][:180]} <a href='#{fn_data['refs'][0]['id']}'>↩</a></li>"
                            ),
                            description=f"Extracted footnote [{num_key}] and linked {len(fn_data['refs'])} bidirectional body reference(s).",
                        )
                    )
            else:
                unlinked_count += 1

        stats.footnotes_linked = linked_count
        stats.footnotes_unlinked = unlinked_count

        for fname, s in soups.items():
            file_notes = {k: v for k, v in g_notes.items() if v["file"] == fname}
            if file_notes:
                sec = s.new_tag(
                    "section",
                    attrs={
                        "epub:type": "footnotes",
                        "style": "margin-top: 3em; border-top: 1px solid #ccc; font-size: 0.9em;",
                    },
                )
                ol = s.new_tag("ol", attrs={"style": "padding-left: 1.5em; list-style-type: none;"})
                for n in sorted(file_notes.keys(), key=int):
                    li = s.new_tag("li", attrs={"id": f"fn-{n}", "style": "margin-bottom: 0.6em;"})
                    p_n = s.new_tag("p", attrs={"style": "text-indent: 0;"})
                    b_num = s.new_tag("strong")
                    b_num.string = f"[{n}] "
                    p_n.append(b_num)
                    fn_frag = BeautifulSoup(file_notes[n].get("html", file_notes[n]["text"]), "html.parser")
                    for child in list(fn_frag.contents):
                        p_n.append(child.extract())
                    p_n.append(NavigableString(" "))
                    refs = file_notes[n]["refs"]
                    alphabet = "abcdefghijklmnopqrstuvwxyz"
                    for i, ref in enumerate(refs):
                        href_back = f"{ref['file']}#{ref['id']}" if ref["file"] != fname else f"#{ref['id']}"
                        bk = s.new_tag(
                            "a",
                            attrs={
                                "href": href_back,
                                "style": "text-decoration: none; color: #3498db; font-weight: bold; margin-right: 5px;",
                            },
                        )
                        bk.string = f"↩{alphabet[i % 26]}" if len(refs) > 1 else "↩"
                        p_n.append(bk)
                    li.append(p_n)
                    ol.append(li)
                sec.append(ol)
                s.body.append(sec)
            (tmp_path / "EPUB" / "text" / fname).write_text(str(s), encoding="utf-8")

        # --- Final Packaging (W3C EPUB 3.3 OCF Compliant) ---
        _package_epub(tmp_path, epub_out)
        log(f"✅ HTML modifications completed ({len(g_notes)} footnotes linked) and EPUB closed.")
        return stats
